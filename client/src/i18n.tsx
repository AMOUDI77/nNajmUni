export type TranslationKey = keyof typeof en;

interface PreferencesContextValue {
  language: Language;
  isArabic: boolean;
  t: (key: TranslationKey) => string;
  toggleLanguage: () => void;
}

const PreferencesContext = createContext<PreferencesContextValue | null>(null);

function getStoredLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  return localStorage.getItem('najmuni_language') === 'ar' ? 'ar' : 'en';
}

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getStoredLanguage);

  useEffect(() => {
    localStorage.setItem('najmuni_language', language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  }, [language]);

  const value = useMemo<PreferencesContextValue>(() => {
    const dictionary = language === 'ar' ? ar : en;
    return {
      language,
      isArabic: language === 'ar',
      t: key => dictionary[key] ?? en[key],
      toggleLanguage: () => setLanguage(prev => prev === 'ar' ? 'en' : 'ar'),
    };
  }, [language]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const ctx = useContext(PreferencesContext);
  if (!ctx) throw new Error('usePreferences must be used within PreferencesProvider');
  return ctx;
}
